create or replace function private.crm_list_system_events_impl(
  p_days integer default 7,
  p_limit integer default 250,
  p_status text default 'all',
  p_search text default ''
)
returns table (
  id bigint,
  source text,
  module text,
  severity text,
  status text,
  message text,
  detail text,
  route text,
  device text,
  app_version text,
  occurrences integer,
  first_seen_at timestamptz,
  last_seen_at timestamptz,
  resolved_at timestamptz,
  reporter_name text
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.current_user_is_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;

  return query
  select e.id, e.source, e.module, e.severity, e.status, e.message, e.detail,
    e.route, e.device, e.app_version, e.occurrences, e.first_seen_at,
    e.last_seen_at, e.resolved_at, coalesce(up.display_name, 'Usuario')
  from public.crm_system_events e
  left join public.user_permissions up on up.user_id = e.reporter_id
  where (coalesce(p_days, 7) <= 0 or e.last_seen_at >= now() - make_interval(days => least(greatest(p_days, 1), 365)))
    and (coalesce(p_status, 'all') = 'all' or e.status = p_status)
    and (
      coalesce(trim(p_search), '') = ''
      or concat_ws(' ', e.source, e.module, e.message, e.detail, e.route, e.device) ilike '%' || left(trim(p_search), 100) || '%'
    )
  order by
    case e.severity when 'critical' then 0 when 'error' then 1 when 'warning' then 2 else 3 end,
    case e.status when 'active' then 0 else 1 end,
    e.last_seen_at desc
  limit least(greatest(coalesce(p_limit, 250), 1), 500);
end;
$$;

