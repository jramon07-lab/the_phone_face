create table if not exists public.crm_system_events (
  id bigint generated by default as identity primary key,
  fingerprint text not null,
  source text not null default 'frontend',
  module text not null default 'general',
  severity text not null default 'error' check (severity in ('info', 'warning', 'error', 'critical')),
  status text not null default 'active' check (status in ('active', 'resolved', 'ignored')),
  message text not null,
  detail text not null default '',
  route text not null default '',
  device text not null default 'unknown',
  app_version text not null default '',
  reporter_id uuid references auth.users(id) on delete set null,
  context jsonb not null default '{}'::jsonb,
  occurrences integer not null default 1 check (occurrences > 0),
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid references auth.users(id) on delete set null
);

create unique index if not exists crm_system_events_active_fingerprint_idx
  on public.crm_system_events (fingerprint) where status = 'active';
create index if not exists crm_system_events_last_seen_idx
  on public.crm_system_events (last_seen_at desc);
create index if not exists crm_system_events_status_severity_idx
  on public.crm_system_events (status, severity, last_seen_at desc);
create index if not exists crm_system_events_reporter_id_idx
  on public.crm_system_events (reporter_id);
create index if not exists crm_system_events_resolved_by_idx
  on public.crm_system_events (resolved_by);

alter table public.crm_system_events enable row level security;

drop policy if exists "Admins read system events" on public.crm_system_events;
create policy "Admins read system events"
  on public.crm_system_events for select to authenticated
  using (public.current_user_is_admin());

drop policy if exists "Admins update system events" on public.crm_system_events;
create policy "Admins update system events"
  on public.crm_system_events for update to authenticated
  using (public.current_user_is_admin())
  with check (public.current_user_is_admin());

revoke all on public.crm_system_events from anon, authenticated;
grant select, update on public.crm_system_events to authenticated;

create or replace function private.crm_report_system_event_impl(
  p_source text,
  p_module text,
  p_severity text,
  p_message text,
  p_detail text default '',
  p_route text default '',
  p_device text default 'unknown',
  p_app_version text default '',
  p_context jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_source text;
  v_module text;
  v_severity text;
  v_message text;
  v_detail text;
  v_route text;
  v_device text;
  v_version text;
  v_context jsonb;
  v_fingerprint text;
  v_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  v_source := case lower(coalesce(p_source, ''))
    when 'desktop' then 'desktop'
    when 'mobile' then 'mobile'
    when 'manual' then 'manual'
    when 'health' then 'health'
    when 'automation' then 'automation'
    else 'frontend'
  end;
  v_module := left(regexp_replace(coalesce(nullif(trim(p_module), ''), 'general'), '[^a-zA-Z0-9_./ -]', '', 'g'), 80);
  v_severity := case lower(coalesce(p_severity, ''))
    when 'info' then 'info'
    when 'warning' then 'warning'
    when 'critical' then 'critical'
    else 'error'
  end;
  v_message := left(coalesce(nullif(trim(p_message), ''), 'Error desconocido'), 500);
  v_detail := left(coalesce(p_detail, ''), 1000);
  v_route := left(split_part(coalesce(p_route, ''), '?', 1), 180);
  v_device := left(regexp_replace(coalesce(nullif(trim(p_device), ''), 'unknown'), '[^a-zA-Z0-9_./ -]', '', 'g'), 60);
  v_version := left(regexp_replace(coalesce(p_app_version, ''), '[^a-zA-Z0-9_.-]', '', 'g'), 80);

  v_message := regexp_replace(v_message, '([?&](token|key|code|password|secret|access_token|refresh_token)=)[^&#[:space:]]+', '\1[REDACTADO]', 'gi');
  v_detail := regexp_replace(v_detail, '([?&](token|key|code|password|secret|access_token|refresh_token)=)[^&#[:space:]]+', '\1[REDACTADO]', 'gi');
  v_detail := regexp_replace(v_detail, '(authorization[[:space:]]*:[[:space:]]*bearer[[:space:]]+)[^[:space:]]+', '\1[REDACTADO]', 'gi');

  v_context := jsonb_strip_nulls(jsonb_build_object(
    'platform', left(coalesce(p_context ->> 'platform', ''), 80),
    'viewport', left(coalesce(p_context ->> 'viewport', ''), 40),
    'online', case when p_context ? 'online' then (p_context -> 'online') else null end,
    'action', left(coalesce(p_context ->> 'action', ''), 100),
    'http_status', case when (p_context ->> 'http_status') ~ '^[0-9]{3}$' then (p_context -> 'http_status') else null end
  ));
  v_fingerprint := md5(concat_ws('|', v_source, lower(v_module), v_severity, lower(v_message), lower(v_route)));

  insert into public.crm_system_events (
    fingerprint, source, module, severity, message, detail, route, device,
    app_version, reporter_id, context
  ) values (
    v_fingerprint, v_source, v_module, v_severity, v_message, v_detail, v_route,
    v_device, v_version, auth.uid(), v_context
  )
  on conflict (fingerprint) where status = 'active'
  do update set
    last_seen_at = now(),
    occurrences = public.crm_system_events.occurrences + 1,
    detail = excluded.detail,
    device = excluded.device,
    app_version = excluded.app_version,
    reporter_id = excluded.reporter_id,
    context = excluded.context,
    severity = case
      when public.crm_system_events.severity = 'critical' or excluded.severity = 'critical' then 'critical'
      when public.crm_system_events.severity = 'error' or excluded.severity = 'error' then 'error'
      when public.crm_system_events.severity = 'warning' or excluded.severity = 'warning' then 'warning'
      else 'info'
    end
  returning id into v_id;

  return v_id;
end;
$$;

