create or replace function private.crm_set_system_event_status_impl(p_id bigint, p_status text)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.current_user_is_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;
  if p_status not in ('active', 'resolved', 'ignored') then
    raise exception 'Invalid status';
  end if;

  update public.crm_system_events
  set status = p_status,
      resolved_at = case when p_status = 'active' then null else now() end,
      resolved_by = case when p_status = 'active' then null else auth.uid() end
  where id = p_id;
  return found;
end;
$$;

