const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const sql=fs.readFileSync(root+'/db/proposals/vodafone-automation-folders-and-review.sql','utf8');
const runner=fs.readFileSync(root+'/supabase/functions/crm-automation-runner/index.ts','utf8');
assert.match(sql,/vodafone_security_3_months/);
assert.match(sql,/vodafone_annual_review/);
assert.match(sql,/'unit','months','value',3/);
assert.match(sql,/'unit','months','value',11/);
assert.match(sql,/permanencias elevadas de 24, 36 o 48 meses/);
assert.doesNotMatch(sql,/después no respetar el precio/);
assert.ok((sql.match(/'business_schedule','phone_house'/g)||[]).length>=2,'day-one and three-month sends must use the business schedule');
assert.match(sql,/REVISIÓN VODAFONE/);
assert.match(sql,/No crea ejecuciones retroactivas/);
assert.match(runner,/job\.action_type==="set_review_date"/);
assert.match(runner,/job\.action_type==="prepare_operator_review"/);
const source=fs.readFileSync(root+'/js/modules/automations-operator-folders.js','utf8');
const window={TPFModules:{register(_n,x){x.install=()=>{};}},crmAutomations:[]};
const document={getElementById:()=>null,addEventListener:()=>{},head:{appendChild:()=>{}}};
vm.runInNewContext(source,{window,document,MutationObserver:function(){},setTimeout:()=>{},console});
const f=window.TPFAutomationFolders;
assert.equal(f.operatorOf({trigger_config:{automation_operator:'Vodafone'}}),'Vodafone');
assert.equal(f.categoryOf({trigger_config:{automation_category:'Posventa'}}),'Posventa');
assert.deepEqual(Array.from(f.order.operators).slice(0,6),['Vodafone','Yoigo','MásMóvil','O2','Lowi','Orange']);
console.log('PASS: Vodafone folders and 3/11-month rules are declared without retroactive jobs.');
