'use strict';
const fs=require('node:fs'),assert=require('node:assert');
const inline=fs.readFileSync('js/modules/contact-google-inline.js','utf8');
const wa=fs.readFileSync('js/modules/whatsapp-ui-fixes.js','utf8');
const html=fs.readFileSync('index.html','utf8');
assert.match(html,/contact-google-inline\.js/,'inline module must be loaded');
assert.match(inline,/Nombre actual de WhatsApp/,'WhatsApp name must be shown');
assert.match(inline,/Guardar unificado/,'single contact correction must update both sources');
assert.match(inline,/available\.length>1/,'multiple Google matches must require a choice');
assert.match(inline,/tpfInlineUseWhatsapp.*apply\([^\n]+,wa\)/,'existing WhatsApp names must be offered as nickname');
assert.match(inline,/c\.nickname\|\|c\.name/,'linked chats must prefer CRM nickname or real name');
assert.match(inline,/waChatRow\.active/,'the active conversation row must stop showing No Name');
assert.match(inline,/Revisar y unificar/,'all linked WhatsApp names must use one unified review');
for(const action of ['Usar datos del CRM','Usar datos de Google','Usar WhatsApp como apodo','Guardar unificado','Ignorar este nombre'])assert.ok(inline.includes(action),`missing unified decision: ${action}`);
assert.match(inline,/Así quedará al guardar/,'the dialog must preview the final result in all three places');
assert.doesNotMatch(inline,/obs\.observe\(document\.body/,'the contact helper must not observe the whole page continuously');
assert.match(wa,/tpfCreateNickname:waName/,'new WhatsApp contacts must put the displayed name in nickname');
assert.match(wa,/tpfCreateFirst:''/,'WhatsApp display name must not be assumed to be the legal name');
console.log('contact Google/WhatsApp inline workflow assertions passed');
