'use strict';
const assert=require('assert'),fs=require('fs');
const O=require('../lib/telegram-operations-core');
const now=new Date('2026-09-11T14:30:00.000Z').getTime();
const manual={id:'m1',status:'pending',whatsapp_enabled:true,customer_name:'Ana',whatsapp_phone:'600000001',whatsapp_message:'Hola Ana',whatsapp_scheduled_at:new Date(now-1000).toISOString(),whatsapp_delivery_status:'pending'};
assert.deepEqual(O.dueManual([manual],{enabledAt:new Date(now-60000).toISOString(),now}).map(x=>x.id),['m1']);
assert.deepEqual(O.dueManual([{...manual,status:'completed'},{...manual,whatsapp_delivery_status:'sent'}],{enabledAt:new Date(now-60000).toISOString(),now}),[]);
assert(O.manualMessage(manual).includes('💬 WhatsApp programado'));
assert(O.manualMessage(manual).includes('Cliente: Ana'));
const job={id:'j1',action_type:'__send_whatsapp',status:'failed',action_config:{text:'Mensaje'},context:{contact_name:'Luis',phone:'611111111'},error_message:'Proveedor no disponible'};
for(const value of ['🚨 Error al enviar WhatsApp','Cliente: Luis','Teléfono: 611111111','Mensaje: Mensaje','Motivo: Proveedor no disponible'])assert(O.failureMessage(job).includes(value));
const summary=O.dailySummary({dayKey:'2026-09-11',sent:12,manualPending:2,errors:0});
for(const value of ['12','2','0'])assert(summary.includes(value));
assert.equal(O.shouldSendDaily(new Date('2026-09-11T18:29:00.000Z').getTime()).due,false);
assert.equal(O.shouldSendDaily(new Date('2026-09-11T18:30:00.000Z').getTime()).due,true);
const vercel=JSON.parse(fs.readFileSync('vercel.json','utf8'));
assert(vercel.crons.some(row=>row.path==='/api/telegram-operations'&&row.schedule==='* * * * *'));
const browser=fs.readFileSync('js/modules/whatsapp-scheduling-core.js','utf8');
const block=browser.slice(browser.indexOf('// WHATSAPP PROGRAMADOS'),browser.indexOf('// AGENDA'));
assert(!block.includes('sendTelegramNotification("whatsapp"'),'El navegador no debe duplicar el Telegram del servidor');
console.log('PASS Telegram operaciones: manuales, fallos, resumen diario y entrega desde servidor.');
